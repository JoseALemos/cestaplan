class IngredientSpec(TypedDict):
    """One canonical ingredient plus the package sizes it is sold in."""

    name: str
    display: str
    cat: str
    unit: str  # base unit: g | ml | unit
    density: float | None  # g per ml (liquids), else None
    allergens: list[str]
    traces: list[str]
    # per-100(g|ml): kcal, protein, carb, sugars, fat, sat_fat, fiber, salt
    nutr: tuple[float, float, float, float, float, float, float, float]
    # each package (quantity in base unit, pack price EUR) -> one catalogue product
    packages: list[tuple[float, str]]


