"""Curated demo dataset for the fictional supermarket ``MercaEjemplo``.

Pure data only — no I/O and no ORM. The seed script (:mod:`cestaplan_api.scripts.seed_demo`)
consumes these tables to build a synthetic catalogue and recipe book. Everything here is
FICTIONAL and must always be stored with ``is_synthetic=True`` / ``source_type='demo'``.

Design invariants that keep the catalogue internally consistent:

- Every recipe ingredient references a ``canonical_name`` that exists in :data:`INGREDIENTS`.
  Each ingredient yields catalogue products with a price, so every recipe is satisfiable.
- Recipe ingredient units always equal the ingredient's ``default_unit`` and every product of
  that ingredient is sold in the same base unit, so the ingredient->product conversion factor
  is exactly ``1`` and the deterministic engine can resolve quantities without ambiguity.
- Nutrition figures are per 100 g (or per 100 ml for liquids); the seed writes them verbatim
  as the ``basis_quantity=100`` nutrition row.
"""

